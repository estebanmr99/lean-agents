// RTK on OpenCode 2 (#478): the v2 adapter runs `rtk init -g --opencode` like 1.x, and --upgrade-agent classifies a 1.x
// plugins/rtk.ts by its content. Synthetic temp HOME; nothing is run.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { inventory } from '../scripts/lib/adopt.mjs';
import { upgradeInventory, formatUpgrade } from '../scripts/lib/upgrade.mjs';
import { opencodeV2Adapter } from '../scripts/lib/adapters/opencode-v2.mjs';
import { loadCore } from '../scripts/lib/render.mjs';

const j = path.join;
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skip = process.platform === 'win32' && 'the real-upgrade job covers Windows paths';
const tmp = () => fs.realpathSync(fs.mkdtempSync(j(os.tmpdir(), 'rtk-oc2-')));

test('opencode-v2 with rtk: the rtk init command and its --uninstall undo, no lean-agents plugin file', () => {
  const home = tmp();
  const opts = (tools) => ({ tools, network: {}, terminals: [], platform: 'linux', env: {}, shell: 'default' });
  const run = (tools) => opencodeV2Adapter({ home, core: loadCore(ROOT), profile: null, opts: opts(tools), rulesPath: j(home, 'rules.md') });
  const r = run(['rtk']);
  const c = r.commands.find((x) => x.tool === 'rtk');
  assert.deepEqual(c.run, [['rtk', 'init', '-g', '--opencode']]);
  assert.deepEqual(c.undo, [['rtk', 'init', '-g', '--opencode', '--uninstall']]);
  assert.ok(!r.actions.some((a) => /plugins[\\/]rtk/.test(a.path)), 'rtk writes its own plugins/rtk.ts; lean-agents owns no file for it');
  assert.equal(run([]).commands.some((x) => x.tool === 'rtk'), false);
  fs.rmSync(home, { recursive: true, force: true });
});

const HEADER = '// RTK OpenCode plugin — rewrites commands to use rtk for token savings.\n';
// Shape of the rtk 0.42 file seen on a real work PC: a bare 1.x hooks object (execute.before), no setup( and no server(.
const OLD = `import type { Plugin } from "@opencode-ai/plugin"\n\n${HEADER}export const RtkOpenCodePlugin: Plugin = async ({ $ }) => ({\n  "tool.execute.before": async (input, output) => {},\n})\n`;
const DUAL = `import { execFile } from "node:child_process"\n\n${HEADER}const P = {\n  id: "rtk",\n  async setup(ctx: any) {},\n  async server() { return {} },\n}\nexport default P\n`;

async function plan(text, tools) {
  const home = tmp();
  fs.mkdirSync(j(home, '.config', 'opencode', 'plugins'), { recursive: true });
  if (text !== null) fs.writeFileSync(j(home, '.config', 'opencode', 'plugins', 'rtk.ts'), text);
  const inv = await inventory({ home, env: { HOME: home, PATH: '' }, platform: process.platform, realHome: '/nowhere' });
  const r = upgradeInventory(inv, { home, tools });
  fs.rmSync(home, { recursive: true, force: true });
  return { up: r.items.find((i) => i.upgrade && i.name === 'plugins/rtk.ts')?.upgrade, plan: r.upgrade.plan, text: formatUpgrade(r) };
}

test('upgrade: an rtk.ts with setup() is kept, and the plan says so', { skip }, async () => {
  for (const tools of [['rtk'], []]) {
    const { up, plan: p } = await plan(DUAL, tools);
    assert.equal(up.class, 'user-translatable');
    assert.match(up.after, /^kept: .*works on 2\.x as is/);
    assert.ok(p.includes('translate plugins/rtk.ts (1.x file) -> kept: it already has the 2.x entry, rtk.ts works on 2.x as is'), p.join('\n'));
  }
});

test('upgrade: a 1.x-only rtk.ts is regenerated by rtk init when rtk is selected', { skip }, async () => {
  const { up, plan: p } = await plan(OLD, ['rtk']);
  assert.equal(up.class, 'user-translatable');
  assert.match(up.after, /regenerated by rtk init -g --opencode \(2\.x-ready, still loads in opencode1\)/);
  assert.ok(p.some((l) => l.startsWith('translate plugins/rtk.ts (1.x-only file) -> regenerated by rtk init')), p.join('\n'));
});

test('upgrade: a 1.x-only rtk.ts is a manual item with the same hint when rtk is not selected', { skip }, async () => {
  const { up, plan: p } = await plan(OLD, []);
  assert.equal(up.class, 'user-manual');
  assert.match(up.reason, /regenerate with rtk init -g --opencode \(2\.x-ready, still loads in opencode1\)/);
  assert.ok(p.some((l) => l.startsWith('manual plugins/rtk.ts (1.x-only file)')), p.join('\n'));
});

test('upgrade: a plugins/rtk.ts without the rtk header stays the generic manual item', { skip }, async () => {
  const { up } = await plan('export default {}\n', ['rtk']);
  assert.equal(up.class, 'user-manual');
  assert.match(up.reason, /not proven/);
});

// After the upgrade the next --update runs the adapter commands, so a saved v2 setup with rtk gets `rtk init -g --opencode` (#478).
const lean = (home, args) => {
  const r = spawnSync(process.execPath, [j(ROOT, 'scripts', 'lean.mjs'), '--home', home, ...args], { encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr || r.stdout);
  return r.stdout;
};
const rtkInit = (out) => JSON.parse(out).commands.filter((c) => c.run.some((a) => a.join(' ') === 'rtk init -g --opencode')).length;

test('--update on a saved opencode-v2 setup with rtk plans rtk init, also when the saved state never had that command', { skip }, () => {
  const home = tmp();
  lean(home, ['--yes', '--no-exec', '--agents', 'opencode-v2', '--tools', 'rtk', '--lang', 'en', '--profile', 'none']);
  const plugins = j(home, '.config', 'opencode', 'plugins');
  fs.mkdirSync(plugins, { recursive: true });
  fs.writeFileSync(j(plugins, 'rtk.ts'), OLD);

  const up = lean(home, ['--upgrade-agent', 'opencode', '--json', '--no-exec']);
  const item = JSON.parse(up).items.find((i) => i.name === 'plugins/rtk.ts');
  assert.match(item.upgrade.after, /regenerated by rtk init -g --opencode/, 'the plan promises the regeneration');
  assert.equal(rtkInit(lean(home, ['--update', '--yes', '--dry-run', '--json', '--no-exec'])), 1, 'and --update delivers it');

  // A state written before this change: rtk in the saved tools, no rtk command recorded.
  const stateFile = j(home, '.config', 'lean-agents', 'state.json');
  const state = JSON.parse(fs.readFileSync(stateFile, 'utf8'));
  state.commands = (state.commands ?? []).filter((c) => c.tool !== 'rtk');
  fs.writeFileSync(stateFile, JSON.stringify(state));
  assert.equal(rtkInit(lean(home, ['--update', '--yes', '--dry-run', '--json', '--no-exec'])), 1);
  fs.rmSync(home, { recursive: true, force: true });
});
